const dicts = { ru, en };

export function t(key: I18nKey, params?: Record<string, string | number>): string {
  let s = dicts[settings.value.language]?.[key] ?? ru[key] ?? key;
  if (params) for (const k in params) s = s.replaceAll(`{${k}}`, String(params[k]));
  return s;
}

/** Pick a value from a {ru, en} pair. */
export function tr(pair: { ru: string; en: string }): string {
  return pair[settings.value.language] ?? pair.ru;
}

export function lang() { return settings.value.language; }
